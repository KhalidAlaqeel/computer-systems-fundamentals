class Stack:
    def __init__(self):
        self.items = []

    def push(self, item):
        self.items.append(item)

    def pop(self):
        if not self.is_empty():
            return self.items.pop()

    def is_empty(self):
        return len(self.items) == 0


class Queue:
    def __init__(self):
        self.items = []

    def enqueue(self, item):
        self.items.append(item)

    def dequeue(self):
        if not self.is_empty():
            return self.items.pop(0)

    def is_empty(self):
        return len(self.items) == 0


# Example usage
stack = Stack()
stack.push(1)
stack.push(2)
print("Stack pop:", stack.pop())

queue = Queue()
queue.enqueue("A")
queue.enqueue("B")
print("Queue dequeue:", queue.dequeue())
